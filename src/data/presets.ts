export function findPreset(text: string): PresetCase | undefined {
  const normalized = text.replace(/\s+/g, '').replace(/[“”"'']/g, '')
  return PRESETS.find((preset) => {
    const target = preset.story.replace(/\s+/g, '').replace(/[“”"'']/g, '')
    return normalized === target || normalized.includes(target.slice(0, 18))
  })
}
